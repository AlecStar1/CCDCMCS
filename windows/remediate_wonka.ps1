<#
.SYNOPSIS
    MINICOP Blue Team Remediation & Hardening: bcvillano/wonka
.DESCRIPTION
    Detects and remediates Golden Ticket attack artifacts and DCSync remnants
    generated by the Wonka automation framework on Windows Active Directory targets.
#>

[CmdletBinding()]
param()

$ErrorActionPreference = "Continue"

Write-Host "======================================================================" -ForegroundColor Cyan
Write-Host "     MINICOP Blue Team Remediation: Wonka Golden Ticket Defense       " -ForegroundColor Cyan
Write-Host "======================================================================" -ForegroundColor Cyan

$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) {
    Write-Error "[FATAL] Administrator privileges required."
    exit 1
}

$backupDir = "C:\Windows\Temp\BlueTeam_Backup_Wonka_$(Get-Date -Format 'yyyyMMdd_HHmmss')"
New-Item -ItemType Directory -Path $backupDir -Force | Out-Null

# ------------------------------------------------------------------------------
# 1. Sweep Mimikatz Dropped Files and DCSync Loot
# ------------------------------------------------------------------------------
Write-Host "`n[*] Hunting for Mimikatz and DCSync artifacts dropped by Wonka..." -ForegroundColor Yellow

$wonkaPaths = @(
    "C:\Windows\System32\mimikatz.exe",
    "C:\Windows\Temp\mimikatz.exe",
    "C:\Windows\Temp\*_dcsync.txt",
    "C:\ProgramData\mimikatz.exe",
    "C:\Users\Public\mimikatz.exe",
    "C:\Users\Public\*.ccache"
)

foreach ($pattern in $wonkaPaths) {
    Get-Item $pattern -ErrorAction SilentlyContinue | ForEach-Object {
        Write-Host "[-] Found Wonka / Mimikatz artifact: $($_.FullName)" -ForegroundColor Red
        Move-Item $_.FullName "$backupDir\" -Force -ErrorAction SilentlyContinue
        Write-Host "[+] Quarantined $($_.Name)" -ForegroundColor Green
    }
}

# ------------------------------------------------------------------------------
# 2. Terminate Running Mimikatz or WinRM Shell Processes (wsh.py)
# ------------------------------------------------------------------------------
Write-Host "`n[*] Checking for active processes related to Wonka / Mimikatz..." -ForegroundColor Yellow
$procNames = @("mimikatz")
foreach ($pn in $procNames) {
    Get-Process -Name $pn -ErrorAction SilentlyContinue | ForEach-Object {
        Write-Host "[-] Terminating active Mimikatz process: PID $($_.Id)" -ForegroundColor Red
        Stop-Process -Id $_.Id -Force -ErrorAction SilentlyContinue
        Write-Host "[+] Process killed." -ForegroundColor Green
    }
}

# ------------------------------------------------------------------------------
# 3. Active Directory krbtgt Assessment & Remediation Guidance
# ------------------------------------------------------------------------------
Write-Host "`n[*] Active Directory Kerberos Ticket-Granting Service (krbtgt) Audit..." -ForegroundColor Yellow

if (Get-Module -ListAvailable -Name ActiveDirectory) {
    Import-Module ActiveDirectory -ErrorAction SilentlyContinue
    if (Get-Module ActiveDirectory) {
        $krbtgt = Get-ADUser -Identity "krbtgt" -Properties PasswordLastSet, msDS-KrbTgtLink -ErrorAction SilentlyContinue
        if ($krbtgt) {
            Write-Host "[*] krbtgt Last Password Set: $($krbtgt.PasswordLastSet)" -ForegroundColor Cyan
            Write-Host "[*] krbtgt Account Enabled:   $($krbtgt.Enabled)" -ForegroundColor Cyan
            
            # Best practice against Golden Tickets:
            # krbtgt password must be reset TWICE with replication in between to invalidate forged tickets.
            Write-Host "`n[!] CRITICAL DEFENSE NOTE FOR BLUE TEAM:" -ForegroundColor Yellow
            Write-Host "    If Wonka performed DCSync, the adversary holds the KRBTGT NTLM/AES keys."
            Write-Host "    To invalidate ALL existing forged Golden Tickets, the krbtgt account"
            Write-Host "    password MUST be reset twice (Microsoft recommends 10 hours apart in"
            Write-Host "    production, or immediately in emergency competition scenarios):"
            Write-Host "    Command: Reset-ComputerMachinePassword / Set-ADAccountPassword -Identity krbtgt" -ForegroundColor Cyan
        }
    }
}

# ------------------------------------------------------------------------------
# 4. Audit WinRM Configuration
# ------------------------------------------------------------------------------
Write-Host "`n[*] Auditing WinRM service (target of wsh.py)..." -ForegroundColor Yellow
if (Get-Service -Name "WinRM" -ErrorAction SilentlyContinue) {
    $winrmState = (Get-Service -Name "WinRM").Status
    Write-Host "[*] WinRM service status: $winrmState" -ForegroundColor Cyan
}

Write-Host "`n[SUCCESS] Wonka remediation audit complete. Artifacts quarantined in $backupDir`n" -ForegroundColor Green
